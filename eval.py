    "import logging\n",
    "import torch\n",
    "import evaluate\n",
    "from transformers import AutoTokenizer, AutoModelForQuestionAnswering\n",
    "from datasets import load_dataset\n",
    "\n",
    "\n",
    "logging.basicConfig(\n",
    "    level=logging.INFO,\n",
    "    format=\"%(asctime)s - %(levelname)s - %(message)s\"\n",
    ")\n",
    "logger = logging.getLogger(__name__)\n",
    "\n",
    "\n",
    "def preprocess_eval(examples, tokenizer):\n",
    "    questions = [q.strip() for q in examples[\"question\"]]\n",
    "\n",
    "    tokenized = tokenizer(\n",
    "        questions,\n",
    "        examples[\"context\"],\n",
    "        truncation=\"only_second\",\n",
    "        max_length=384,\n",
    "        stride=128,\n",
    "        padding=\"max_length\",\n",
    "        return_overflowing_tokens=True,\n",
    "    )\n",
    "\n",
    "    sample_mapping = tokenized.pop(\"overflow_to_sample_mapping\")\n",
    "    tokenized[\"example_id\"] = [examples[\"id\"][i] for i in sample_mapping]\n",
    "    return tokenized\n",
    "\n",
    "\n",
    "def select_best_span(start_logits, end_logits, input_ids, tokenizer, top_k=10, max_answer_length=30):\n",
    "    start_top = torch.topk(start_logits, top_k)\n",
    "    end_top = torch.topk(end_logits, top_k)\n",
    "\n",
    "    best_score = -1e9\n",
    "    best_span = (0, 0)\n",
    "    cls_score = start_logits[0] + end_logits[0]\n",
    "\n",
    "    for i in range(top_k):\n",
    "        for j in range(top_k):\n",
    "            s = start_top.indices[i].item()\n",
    "            e = end_top.indices[j].item()\n",
    "\n",
    "            if e < s:\n",
    "                continue\n",
    "            if (e - s + 1) > max_answer_length:\n",
    "                continue\n",
    "\n",
    "            score = start_logits[s] + end_logits[e]\n",
    "            if score > best_score:\n",
    "                best_score = score\n",
    "                best_span = (s, e)\n",
    "\n",
    "    if best_score <= cls_score:\n",
    "        return \"\", cls_score\n",
    "\n",
    "    answer_ids = input_ids[best_span[0]: best_span[1] + 1]\n",
    "    text = tokenizer.decode(answer_ids, skip_special_tokens=True).strip()\n",
    "    return text, best_score\n",
    "\n",
    "\n",
    "def main():\n",
    "    logger.info(\"Loading trained model\")\n",
    "    model_path = \"./qa_model_2_roberta\"\n",
    "    tokenizer = AutoTokenizer.from_pretrained(model_path)\n",
    "    model = AutoModelForQuestionAnswering.from_pretrained(model_path)\n",
    "    model.eval()\n",
    "\n",
    "    logger.info(\"Loading validation data\")\n",
    "    data = load_dataset(\"squad_v2\")\n",
    "    val_data = data[\"validation\"].shuffle(seed=42).select(range(5000))\n",
    "\n",
    "    logger.info(\"Tokenizing validation data\")\n",
    "    tokenized_eval = val_data.map(\n",
    "        lambda x: preprocess_eval(x, tokenizer),\n",
    "        batched=True,\n",
    "        remove_columns=val_data.column_names,\n",
    "    )\n",
    "\n",
    "    logger.info(\"Running inference\")\n",
    "    best_per_example = {}\n",
    "\n",
    "    with torch.no_grad():\n",
    "        for row in tokenized_eval:\n",
    "            input_ids = torch.tensor(row[\"input_ids\"]).unsqueeze(0)\n",
    "            attention_mask = torch.tensor(row[\"attention_mask\"]).unsqueeze(0)\n",
    "\n",
    "            outputs = model(input_ids=input_ids, attention_mask=attention_mask)\n",
    "            start_logits = outputs.start_logits[0]\n",
    "            end_logits = outputs.end_logits[0]\n",
    "\n",
    "            pred_text, score = select_best_span(\n",
    "                start_logits, end_logits, row[\"input_ids\"], tokenizer\n",
    "            )\n",
    "\n",
    "            ex_id = row[\"example_id\"]\n",
    "            if (ex_id not in best_per_example) or (score > best_per_example[ex_id][\"score\"]):\n",
    "                best_per_example[ex_id] = {\"text\": pred_text, \"score\": score}\n",
    "\n",
    "    logger.info(\"Computing EM / F1\")\n",
    "    predictions, references = [], []\n",
    "\n",
    "    for ex in val_data:\n",
    "        ex_id = ex[\"id\"]\n",
    "        predictions.append({\n",
    "            \"id\": ex_id,\n",
    "            \"prediction_text\": best_per_example.get(ex_id, {\"text\": \"\"})[\"text\"],\n",
    "            \"no_answer_probability\": 0.0,\n",
    "        })\n",
    "        references.append({\"id\": ex_id, \"answers\": ex[\"answers\"]})\n",
    "\n",
    "    squad_metric = evaluate.load(\"squad_v2\")\n",
    "    results = squad_metric.compute(predictions=predictions, references=references)\n",
    "    logger.info(f\"Evaluation results: {results}\")\n",
    "\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    main()\n"
